/** 番号を1つ選ぶ。すでに出たもの(used)は、全部出るまで出さない。全部出たら、はじめから */
export function drawIndex(length: number, used: ReadonlySet<number>, rand: Rand = Math.random): { index: number; reset: boolean } {
  let pool = Array.from({ length }, (_, i) => i).filter((i) => !used.has(i));
  const reset = pool.length === 0;
  if (reset) pool = Array.from({ length }, (_, i) => i);
  return { index: pool[Math.floor(rand() * pool.length)], reset };
}

